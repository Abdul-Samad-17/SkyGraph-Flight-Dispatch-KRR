"""Runs a fixed set of dispatcher requests through the copilot and stores the transcripts (Results/copilot_demo.md)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from copilot import Copilot, render

QS = [
 "Find an alternate route avoiding the storm over sector Y for an A380 from Lahore to Doha",
 "Find an alternate route from Karachi to Dubai for a B737-800 avoiding the Restricted Zone Alpha",
 "Find a route from Islamabad to London for an A320",
 "Why can't an A380 fly Karachi to Dubai direct?",
 "Diversion candidates for scenario S1",
 "Diversion candidates for scenario S6",
 "An A320 needs to divert: 800 km remaining at position 38.0, 45.0",
 "Route from Islamabad to Gilgit for an ATR72",
 "Which airports are hubs?",
]


def main():
    cp = Copilot()
    out = ["# Copilot demo transcripts (offline mode, no LLM)", "",
           "Generated by `src/demo_transcripts.py`. With ANTHROPIC_API_KEY set, the ANSWER text is rewritten by an LLM and re-validated against the KG; the evidence and routes are identical.", ""]
    for q in QS:
        o = cp.answer(q, use_llm=False)
        out += ["```", render(o, show_sparql=True), "```", ""]
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Results", "copilot_demo.md")
    open(path, "w", encoding="utf-8").write("\n".join(out))
    print("wrote", os.path.abspath(path))


if __name__ == "__main__":
    main()
